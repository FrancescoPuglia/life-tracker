import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const functionsRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = resolve(functionsRoot, '..');
const generatedRoot = resolve(functionsRoot, '.generated');

const inputs = [
  ...(await sourceFiles(resolve(functionsRoot, 'src'))),
  resolve(functionsRoot, 'package.json'),
  resolve(functionsRoot, 'package-lock.json'),
  resolve(functionsRoot, 'build/release-id.mjs'),
  resolve(generatedRoot, 'shared-validators.cjs'),
  resolve(repositoryRoot, 'packages/ai-contract/index.js'),
  resolve(repositoryRoot, 'packages/ai-contract/index.d.ts'),
].sort();

const hash = createHash('sha256');
for (const path of inputs) {
  const content = await readFile(path);
  hash.update(relative(repositoryRoot, path).replaceAll('\\', '/'));
  hash.update('\0');
  hash.update(String(content.byteLength));
  hash.update('\0');
  hash.update(content);
  hash.update('\0');
}
const releaseId = `sha256:${hash.digest('hex')}`;

await mkdir(generatedRoot, { recursive: true });
await writeFile(
  resolve(generatedRoot, 'release-id.ts'),
  `// Generated by build/release-id.mjs; do not edit.\nexport const BACKEND_SOURCE_FINGERPRINT = ${JSON.stringify(releaseId)};\n`,
  'utf8',
);
await writeFile(
  resolve(generatedRoot, 'release-id.json'),
  `${JSON.stringify({ releaseId }, null, 2)}\n`,
  'utf8',
);
process.stdout.write(`Generated backend source fingerprint ${releaseId}\n`);

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await sourceFiles(path));
    else if (entry.isFile() && entry.name.endsWith('.ts')) files.push(path);
  }
  return files;
}
